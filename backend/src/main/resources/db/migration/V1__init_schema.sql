-- =====================================================================
-- 「此刻校园」校园信息共享与生活地图系统 - 初始化表结构（PostgreSQL）
-- 说明：
--   1. 由 Flyway 管理，Hibernate 仅做 validate，保证「实体 = 表结构」一致；
--   2. 经纬度使用 double precision 存储，配合球面 Haversine 公式进行空间检索，
--      即使未安装 PostGIS 也能运行；如需 PostGIS 空间索引与 ST_DWithin 加速，
--      可执行 db/optional_postgis.sql（可选升级路径）；
--   3. 时间统一使用 timestamp（服务器标准时间）。
-- =====================================================================

-- 学校（多租户维度）
CREATE TABLE school (
    school_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code             VARCHAR(50)  NOT NULL UNIQUE,
    name             VARCHAR(100) NOT NULL,
    city             VARCHAR(50),
    center_latitude  DOUBLE PRECISION NOT NULL,
    center_longitude DOUBLE PRECISION NOT NULL,
    default_zoom     INTEGER      NOT NULL DEFAULT 16,
    status           VARCHAR(20)  NOT NULL DEFAULT 'ENABLED',
    created_at       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 用户（校园普通用户 / 平台管理员）
CREATE TABLE app_user (
    user_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_id     BIGINT,
    username      VARCHAR(50)  NOT NULL UNIQUE,
    nickname      VARCHAR(50)  NOT NULL,
    password_hash VARCHAR(200) NOT NULL,
    avatar        VARCHAR(255),
    contact       VARCHAR(100),
    role          VARCHAR(20)  NOT NULL DEFAULT 'USER',
    status        VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    credit_score  INTEGER      NOT NULL DEFAULT 100,
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_user_school FOREIGN KEY (school_id) REFERENCES school (school_id)
);

-- 信息分类（可由后台配置：名称、默认有效期、排序、启用状态）
CREATE TABLE category (
    category_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            VARCHAR(50) NOT NULL UNIQUE,
    name            VARCHAR(50) NOT NULL,
    description     VARCHAR(255),
    icon            VARCHAR(50),
    color           VARCHAR(20),
    base_valid_days INTEGER     NOT NULL DEFAULT 7,
    sort_order      INTEGER     NOT NULL DEFAULT 0,
    status          VARCHAR(20) NOT NULL DEFAULT 'ENABLED',
    created_at      TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 校园地点
CREATE TABLE campus_location (
    location_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_id   BIGINT           NOT NULL,
    name        VARCHAR(100)     NOT NULL,
    area        VARCHAR(50),
    latitude    DOUBLE PRECISION NOT NULL,
    longitude   DOUBLE PRECISION NOT NULL,
    description VARCHAR(255),
    status      VARCHAR(20)      NOT NULL DEFAULT 'VERIFIED',
    created_at  TIMESTAMP        NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP,
    CONSTRAINT fk_location_school FOREIGN KEY (school_id) REFERENCES school (school_id)
);

-- 信息帖子（地图上的信息节点）
CREATE TABLE post (
    post_id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_id          BIGINT           NOT NULL,
    category_id        BIGINT           NOT NULL,
    location_id        BIGINT,
    user_id            BIGINT           NOT NULL,
    title              VARCHAR(200)     NOT NULL,
    content            VARCHAR(4000)    NOT NULL,
    latitude           DOUBLE PRECISION,
    longitude          DOUBLE PRECISION,
    contact            VARCHAR(100),
    image_url          VARCHAR(500),
    tags               VARCHAR(255),
    ai_assisted        BOOLEAN          NOT NULL DEFAULT FALSE,
    expire_at          TIMESTAMP        NOT NULL,
    status             VARCHAR(20)      NOT NULL DEFAULT 'PUBLISHED',
    verify_true_count  INTEGER          NOT NULL DEFAULT 0,
    verify_false_count INTEGER          NOT NULL DEFAULT 0,
    view_count         INTEGER          NOT NULL DEFAULT 0,
    comment_count      INTEGER          NOT NULL DEFAULT 0,
    like_count         INTEGER          NOT NULL DEFAULT 0,
    report_count       INTEGER          NOT NULL DEFAULT 0,
    hot_score          DOUBLE PRECISION NOT NULL DEFAULT 0,
    version            BIGINT           NOT NULL DEFAULT 0,
    audit_by           BIGINT,
    audited_at         TIMESTAMP,
    audit_remark       VARCHAR(255),
    created_at         TIMESTAMP        NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at         TIMESTAMP        NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_post_school FOREIGN KEY (school_id) REFERENCES school (school_id),
    CONSTRAINT fk_post_category FOREIGN KEY (category_id) REFERENCES category (category_id),
    CONSTRAINT fk_post_location FOREIGN KEY (location_id) REFERENCES campus_location (location_id),
    CONSTRAINT fk_post_user FOREIGN KEY (user_id) REFERENCES app_user (user_id)
);

-- 评论
CREATE TABLE comment (
    comment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id    BIGINT        NOT NULL,
    user_id    BIGINT        NOT NULL,
    content    VARCHAR(1000) NOT NULL,
    status     VARCHAR(20)   NOT NULL DEFAULT 'ENABLED',
    created_at TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_comment_post FOREIGN KEY (post_id) REFERENCES post (post_id),
    CONSTRAINT fk_comment_user FOREIGN KEY (user_id) REFERENCES app_user (user_id)
);

-- 协同验证（同一用户对同一信息只能有一条记录 -> 状态互斥）
CREATE TABLE verification (
    verification_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id         BIGINT      NOT NULL,
    user_id         BIGINT      NOT NULL,
    result          VARCHAR(20) NOT NULL,
    remark          VARCHAR(255),
    created_at      TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_verification_post FOREIGN KEY (post_id) REFERENCES post (post_id),
    CONSTRAINT fk_verification_user FOREIGN KEY (user_id) REFERENCES app_user (user_id),
    CONSTRAINT uk_verification_post_user UNIQUE (post_id, user_id)
);

-- 点赞 / 互动
CREATE TABLE post_like (
    like_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id    BIGINT    NOT NULL,
    user_id    BIGINT    NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_like_post FOREIGN KEY (post_id) REFERENCES post (post_id),
    CONSTRAINT fk_like_user FOREIGN KEY (user_id) REFERENCES app_user (user_id),
    CONSTRAINT uk_like_post_user UNIQUE (post_id, user_id)
);

-- 举报
CREATE TABLE report (
    report_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id       BIGINT       NOT NULL,
    user_id       BIGINT       NOT NULL,
    reason        VARCHAR(100) NOT NULL,
    detail        VARCHAR(500),
    status        VARCHAR(20)  NOT NULL DEFAULT 'PENDING',
    handled_by    BIGINT,
    handled_at    TIMESTAMP,
    handle_remark VARCHAR(255),
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_report_post FOREIGN KEY (post_id) REFERENCES post (post_id),
    CONSTRAINT fk_report_user FOREIGN KEY (user_id) REFERENCES app_user (user_id)
);

-- 失物招领认领申请
CREATE TABLE claim (
    claim_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id       BIGINT       NOT NULL,
    user_id       BIGINT       NOT NULL,
    description   VARCHAR(500) NOT NULL,
    contact       VARCHAR(100),
    status        VARCHAR(20)  NOT NULL DEFAULT 'PENDING',
    handled_by    BIGINT,
    handled_at    TIMESTAMP,
    handle_remark VARCHAR(255),
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_claim_post FOREIGN KEY (post_id) REFERENCES post (post_id),
    CONSTRAINT fk_claim_user FOREIGN KEY (user_id) REFERENCES app_user (user_id)
);

-- 操作日志（发布、审核、举报处理、过期治理等关键动作留痕）
CREATE TABLE operation_log (
    log_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operator_id   BIGINT,
    operator_name VARCHAR(50),
    action        VARCHAR(50) NOT NULL,
    target_type   VARCHAR(50),
    target_id     BIGINT,
    detail        VARCHAR(500),
    result        VARCHAR(20) DEFAULT 'SUCCESS',
    created_at    TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 定时任务执行记录
CREATE TABLE task_record (
    task_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_name      VARCHAR(100) NOT NULL,
    task_type      VARCHAR(50)  NOT NULL,
    status         VARCHAR(20)  NOT NULL DEFAULT 'RUNNING',
    affected_count INTEGER      NOT NULL DEFAULT 0,
    message        VARCHAR(500),
    started_at     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    finished_at    TIMESTAMP
);

-- 登录令牌
CREATE TABLE auth_token (
    token          VARCHAR(64) PRIMARY KEY,
    user_id        BIGINT      NOT NULL,
    issued_at      TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at     TIMESTAMP   NOT NULL,
    last_access_at TIMESTAMP,
    CONSTRAINT fk_token_user FOREIGN KEY (user_id) REFERENCES app_user (user_id)
);

-- 索引：覆盖地图视野查询、搜索与后台列表的常见访问路径
CREATE INDEX idx_post_school_status_expire ON post (school_id, status, expire_at);
CREATE INDEX idx_post_school_category ON post (school_id, category_id);
CREATE INDEX idx_post_location ON post (location_id);
CREATE INDEX idx_post_created_at ON post (created_at DESC);
CREATE INDEX idx_post_hot_score ON post (hot_score DESC);
CREATE INDEX idx_post_bounds ON post (school_id, latitude, longitude);
CREATE INDEX idx_location_school ON campus_location (school_id, name);
CREATE INDEX idx_comment_post ON comment (post_id, created_at);
CREATE INDEX idx_verification_post ON verification (post_id);
CREATE INDEX idx_report_status ON report (status, created_at DESC);
CREATE INDEX idx_claim_post ON claim (post_id, created_at DESC);
CREATE INDEX idx_log_created_at ON operation_log (created_at DESC);
CREATE INDEX idx_token_user ON auth_token (user_id);

